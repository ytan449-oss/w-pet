export const getDictionary = (locale: Locale): Dictionary => locale === "zh" ? zh : en;

export async function requireLocale(params: Promise<{ locale: string }>): Promise<Locale> {
  const { locale } = await params;
  if (!isLocale(locale)) notFound();
  return locale;
}
